import { describe, expect, it } from "vitest";
import openapiTS, { astToString } from "openapi-typescript";
import schema from "./schema.d.ts?raw";
import snapshot from "../../../openapi/openapi.json?raw";

// What the openapi-typescript CLI writes above the generated code.
const HEADER = "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n";

describe("generated API types", () => {
  it("schema.d.ts is what openapi/openapi.json generates (run `npm run api:gen` after changing the snapshot)", async () => {
    const generated = astToString(await openapiTS(JSON.parse(snapshot)));
    expect(schema.trimEnd()).toBe((HEADER + generated).trimEnd());
  }, 60_000);
});
